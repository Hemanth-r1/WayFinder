// Serializable versions — Maps converted to arrays for JSON transfer

export interface RoadNode {
  id: string; lat: number; lng: number; trafficSignalId?: string;
}

export interface RoadEdge {
  id: string; from: string; to: string;
  name: string; roadType: string; speedLimit: number; length: number;
  bearing: number; lanes: number; geometry: { lat: number; lng: number }[];
  /** Capacity multiplier at known choke points (e.g. 0.5 near Silk Board); 1 when absent */
  bottleneck?: number;
  /** Position in the simulation's per-edge arrays (set by the engine) */
  ix?: number;
  /** Flyover / elevated road (OSM bridge with layer ≥ 1, or a named flyover) */
  elevated?: boolean;
}

/** A named neighbourhood (OSM place=suburb/neighbourhood/…), used to describe directions. */
export interface Place {
  name: string;
  lat: number;
  lng: number;
}

export interface RoadGraph {
  nodes: RoadNode[];
  edges: RoadEdge[];
  adjacency: [string, string[]][];
}

export interface SignalPhase {
  group: string; color: string; duration: number; yellowDuration: number;
}

export interface SignalApproach {
  edgeId: string;
  /** Arrival bearing (degrees) */
  bearing: number;
  /** Phase group serving this approach ('A' main road, 'B' cross road); 'FREE' = inside the junction, no stop */
  group: string;
}

/** One direction of traffic at a junction, described for people. */
export interface SignalArm {
  /** Approach road (edge) and the phase group that lets it go */
  edgeId: string;
  group: string;
  road: string;
  /** Where traffic comes from and is heading, as compass words ("south-east") */
  from: string;
  heading: string;
  /** Straight-ahead destination: next junction or road name */
  towards: string;
  /** Previous junction on this road, if within 1.5 km */
  fromJunction?: string;
  lanes: number;
}

export interface TrafficSignal {
  /**
   * Permanent junction ID ("J" + the OSM id of its main stop line, base 36), stable
   * across map refreshes; nodeId = representative node (drawn on the map)
   */
  id: string; nodeId: string;
  /** Junction name: OSM name if tagged, else the crossing roads ("Hosur Road × Outer Ring Road") */
  name?: string;
  /** Every stop-line node this controller runs (defaults to [nodeId]) */
  nodeIds?: string[];
  /** Bearing of the junction's main road; group 'A' runs along it */
  axis?: number;
  phases: SignalPhase[];
  currentPhaseIndex: number; timer: number;
  cycleLength: number; offset: number;
  greenWaveDirection: string | null;
  congestionLevel: number; adaptiveTiming: boolean;
  approaches: SignalApproach[];
  /** Each direction of traffic in plain words (set once the junction network is built) */
  arms?: SignalArm[];
}

export interface Vehicle {
  id: string; lat: number; lng: number;
  speed: number; bearing: number;
  type: string; color: string;
  isNavigated: boolean;
  /** Riding against a one-way */
  wrongWay?: boolean;
  /** Ran a red light in the last few seconds */
  violation?: boolean;
}

export interface CongestionZone {
  centerLat: number; centerLng: number;
  level: number; vehicles: number;
}

export interface TrafficStats {
  totalVehicles: number; avgSpeed: number; avgDelay: number;
  congestionHotspots: number; greenWaveActive: boolean;
  signalCoordinationScore: number; throughput: number; maxCongestion: number;
  slaSpeed: number; slaCompliant: boolean;
  emergencySlaSpeed: number; activeCorridors: number;
  /** Vehicles generated by the simulation */
  simulatedVehicles?: number;
  /** Vehicles of navigating users (GPS-driven or simulated drive) */
  realVehicles?: number;
  /** Vehicles waiting at a red light */
  atSignal?: number;
  /** Vehicles stopped in queues (not at a red light) */
  queued?: number;
  /** Vehicles riding against a one-way right now */
  wrongWay?: number;
  /** Red lights jumped in the last 5 minutes */
  redJumps?: number;
  /** Buses and autos stopped at the kerb for passengers */
  kerbStops?: number;
}

export interface RouteInfo {
  /** Node IDs from source to destination */
  path: string[];
  /** Directed edge IDs traversed, in order */
  edgeIds: string[];
  /** Metres */
  distance: number;
  /** Seconds, including live congestion, other navigators and signal delay */
  estimatedTime: number;
  signalCount: number;
  /** Distinct road names in travel order */
  roadNames: string[];
  /** Full road geometry for drawing */
  geometry: { lat: number; lng: number }[];
  /** Most other active navigators sharing any single edge of this route */
  sharedUsers: number;
}
